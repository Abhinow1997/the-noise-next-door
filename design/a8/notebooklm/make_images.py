from PIL import Image, ImageDraw, ImageFont

REPO = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent / "images"
RAW = OUT / "raw"
FONTS = REPO.parent / "brutalist.art" / "runtime" / "fonts" / "Inter" / "static"
WIDTH = 1280

