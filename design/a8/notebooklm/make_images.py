"""Make the Assignment 8 NotebookLM pack's pictures: each a copy of a picture in the repo with a
caption bar under it saying what it is (REAL GAME, FIXTURE CAPTURE, GENERATED or CONSTRUCTED),
what it shows, and its date and commit. The bar sits under the picture, not over it, so the
picture isn't covered, and the label goes wherever NotebookLM puts the image.

Run from the repo root with Pillow (Brutalist's venv has it), after converting the storyboard:
    godot --headless --path . --script res://tools/svg_to_png.gd -- 1280 design/a8/notebooklm/images/raw \\
        design/storyboard/storyboard-sheet.svg design/storyboard/08-the-red-beanie.svg \\
        design/storyboard/11-barking-up-the-wrong-tree.svg design/storyboard/14-home-at-last.svg
    python3 design/a8/notebooklm/make_images.py
"""
